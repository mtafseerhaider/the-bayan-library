"""Retrieval index generation.

The index is the repository memory that agents read instead of files. It
is sharded by node type so that a task loads only the shard it needs:

* metadata/index.yaml            manifest (counts, shard paths, totals)
* metadata/index/<type>.jsonl    one card per record, sorted by ID

Each card carries token estimates for every retrieval layer, so the
context builder can plan a budget before reading a single file. Output is
deterministic (no timestamps) so `--check` can detect drift in CI.
"""

from __future__ import annotations

import json
from pathlib import Path

from .common import dump_yaml, estimate_tokens, read_optional, rel
from .metadata import Library, Record

SUMMARY_FIELDS = ("summary", "description", "definition")


def card(record: Record, root: Path) -> dict:
    data = record.data
    summary = next((data[f] for f in SUMMARY_FIELDS if data.get(f)), "")
    entry = {
        "id": record.id,
        "type": record.type,
        "title": data.get("title") or data.get("name") or record.id,
        "summary": " ".join(str(summary).split()),
        "tags": sorted(data.get("tags", []) or []),
        "civilization": data.get("civilization"),
        "status": data.get("status", "draft"),
        "record": rel(record.path, root),
        "executive_summary": data.get("executive_summary_path"),
        "content": data.get("content_path"),
    }
    entry = {k: v for k, v in entry.items() if v not in (None, "", [])}
    entry["tokens"] = {
        "card": 0,
        "summary": estimate_tokens(entry.get("summary", "")),
        "executive": estimate_tokens(read_optional(root, entry.get(
            "executive_summary"))),
        "full": estimate_tokens(read_optional(root, entry.get("content"))),
    }
    entry["tokens"]["card"] = estimate_tokens(json.dumps(
        {k: v for k, v in entry.items() if k not in ("summary", "tokens")},
        ensure_ascii=False))
    return entry


def build(lib: Library) -> dict[str, str]:
    """Return {relative path: file content} for the whole index."""
    files: dict[str, str] = {}
    manifest = {
        "generated_by": "scripts/build-index.py",
        "version": 1,
        "retrieval_ladder": ["card", "summary", "executive", "full"],
        "types": {},
        "totals": {"records": 0, "card_tokens": 0},
    }
    types = sorted({r.type for r in lib.records.values()})
    for node_type in types:
        cards = [card(r, lib.root) for r in lib.by_type(node_type)]
        shard = f"metadata/index/{node_type}.jsonl"
        files[shard] = "".join(json.dumps(c, ensure_ascii=False,
                                          sort_keys=True) + "\n"
                               for c in cards)
        card_tokens = sum(c["tokens"]["card"] for c in cards)
        manifest["types"][node_type] = {
            "count": len(cards),
            "shard": shard,
            "card_tokens": card_tokens,
        }
        manifest["totals"]["records"] += len(cards)
        manifest["totals"]["card_tokens"] += card_tokens
    manifest["relationships"] = len(lib.relationships)
    files["metadata/index.yaml"] = (
        "# Generated by scripts/build-index.py. Do not edit by hand.\n"
        + dump_yaml(manifest))
    return files


def write(lib: Library, files: dict[str, str]) -> list[str]:
    changed = []
    index_dir = lib.root / "metadata" / "index"
    for stale in sorted(index_dir.glob("*.jsonl")) if index_dir.is_dir() \
            else []:
        if rel(stale, lib.root) not in files:
            stale.unlink()
            changed.append(rel(stale, lib.root))
    for name, content in files.items():
        path = lib.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8")
            changed.append(name)
    return changed


def drift(lib: Library, files: dict[str, str]) -> list[str]:
    problems = []
    for name, content in files.items():
        path = lib.root / name
        if not path.is_file():
            problems.append(f"{name} is missing")
        elif path.read_text(encoding="utf-8") != content:
            problems.append(f"{name} is out of date")
    index_dir = lib.root / "metadata" / "index"
    if index_dir.is_dir():
        for stale in index_dir.glob("*.jsonl"):
            if rel(stale, lib.root) not in files:
                problems.append(f"{rel(stale, lib.root)} is stale")
    return problems
